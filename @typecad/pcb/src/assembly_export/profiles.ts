/**
 * Provider profiles for assembly outputs (placement/centroid + BOM files).
 *
 * A profile is data, not code: one writer consumes these knobs, so a new
 * provider is a new object here — no branching logic grows anywhere else.
 *
 * Two conventions matter and are deliberately conservative:
 *
 * - Coordinate frame: every profile emits KiCad board coordinates as-is
 *   (mm, Y-down from the board origin). JLCPCB, PCBWay and Seeed all
 *   ingest KiCad-native files directly and adapt the frame on their side —
 *   PCBWay explicitly asks customers NOT to pre-mirror bottom-side data
 *   (the CAD-native convention is what their importer expects).
 * - Bottom-side rotation: emitted exactly as the board stores it. The
 *   0°-vs-180° ambiguity for mirrored parts is a per-assembler decision;
 *   `--bottom-rotation` overrides for shops that ask for an offset.
 *
 * Sources: JLCPCB help "How To Export BOM and CPL Files From KiCad"
 * (Designator / Mid X / Mid Y / Layer / Rotation, mm, negative Y fine),
 * PCBWay "PCB Assembly File Requirements", Seeed Fusion PCBA guidelines
 * (same CPL family), OpenPnP's Reference CSV importer (id,x,y,rotation,side,
 * side spelled Top/Bottom).
 */

/** Which per-part datum a placement row reports. */
export type CentroidMode = 'anchor' | 'pads' | 'body';

export type PlacementColumnKey = 'ref' | 'value' | 'footprint' | 'x' | 'y' | 'rotation' | 'side';

export interface PlacementProfile {
  id: string;
  /** Human name for help text and logs. */
  label: string;
  /** Output file: `<board-stem><fileSuffix>`. */
  fileSuffix: string;
  /** Comment lines above the CSV (called with the units actually used). */
  comments?: (units: string) => string[];
  delimiter: string;
  columns: { key: PlacementColumnKey; header: string }[];
  /** `always` quotes every field (KiCad's own CSV does); `minimal` is RFC 4180. */
  quote: 'always' | 'minimal';
  units: 'mm' | 'in' | 'mils';
  decimals: number;
  /** Rotation decimals (JLC-style shops parse integers; keep ≥ 0). */
  rotationDecimals: number;
  side: { front: string; back: string };
  /** Rotation added to every part, degrees. */
  rotationOffset: number;
  /** Extra rotation added to bottom-side parts only, degrees. */
  bottomRotation: number;
  /**
   * OpenPnP's KiCad convention: bottom-side x is negated and the rotation
   * mirrored (rot → 180 − rot) — the board flipped about the Y axis to show
   * its bottom. Mirrors KicadPosImporter in OpenPnP's source.
   */
  flipBottomX?: boolean;
  mirrorBottomRotation?: boolean;
  /** Also write a native OpenPnP `.board.xml` beside the CSV. */
  boardXml?: boolean;
  /** Default centroid datum (`generic` follows the --centroid flag). */
  centroid: CentroidMode;
  /** Ref globs kept out of the placement file (fiducials, mounting holes). */
  exclude: string[];
  /** Ref globs emitted as fiducial placements (OpenPnP aligns on these). */
  fiducials?: string[];
  /** Emit DNP footprints (KiCad's pos export does). */
  includeDnp: boolean;
}

export type BomColumnKey =
  | 'comment'
  | 'refs'
  | 'qty'
  | 'value'
  | 'footprint'
  | 'mpn'
  | 'datasheet'
  | 'side'
  | 'ref';

export interface BomProfile {
  id: string;
  /** Human name for help text and logs. */
  label: string;
  fileSuffix: string;
  delimiter: string;
  columns: { key: BomColumnKey; header: string }[];
  quote: 'always' | 'minimal';
  /** Collapsed rows (refs joined) vs one row per reference. */
  grouped: boolean;
  /** Ref globs kept out of the BOM (fiducials, mounting holes). */
  exclude: string[];
}

