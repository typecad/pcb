import type { ParsedArgs } from '../parser.js';
import logger from '../../../utils/logging.js';
import { COMMANDS, displayFlag, GLOBAL_FLAGS } from '../registry.js';

type Shell = 'bash' | 'zsh' | 'pwsh';

const SHELL_NAMES: Record<string, Shell> = { bash: 'bash', zsh: 'zsh', pwsh: 'pwsh', powershell: 'pwsh' };

/** Flags shown for every command (`--version`, `--out-dir`, `--outdir` are noise in a completion list). */
const GLOBAL_COMPLETION_FLAGS = GLOBAL_FLAGS.filter((f) => !['version', 'out-dir', 'outdir'].includes(f)).map(displayFlag);

interface CompletionEntry {
  name: string;
  summary: string;
  subs: string[];
  flags: string[];
}

/** What every shell script is generated from: the command registry. */
export function completionEntries(): CompletionEntry[] {
  return COMMANDS.map((spec) => ({
    name: spec.name,
    summary: spec.summary,
    subs: (spec.subcommands ?? []).map((s) => s.name),
    flags: [...new Set([...spec.flags.map(displayFlag), ...GLOBAL_COMPLETION_FLAGS])],
  }));
}

function bashScript(entries: CompletionEntry[]): string {
  const names = [...entries.map((e) => e.name), 'help'].join(' ');
  const cases = entries
    .map((e) => `    ${e.name}) subs="${e.subs.join(' ')}"; flags="${e.flags.join(' ')}" ;;`)
    .join('\n');
  return [
    '# typecad-pcb bash completion — generated by `typecad-pcb completion bash`',
    '_typecad_pcb() {',
    '  local cur cmd subs flags',
    '  cur="${COMP_WORDS[COMP_CWORD]}"',
    '  if [ "$COMP_CWORD" -eq 1 ]; then',
    `    COMPREPLY=( $(compgen -W "${names}" -- "$cur") )`,
    '    return',
    '  fi',
    '  cmd="${COMP_WORDS[1]}"',
    '  subs=""',
    `  flags="${GLOBAL_COMPLETION_FLAGS.join(' ')}"`,
    '  case "$cmd" in',
    cases,
    '  esac',
    '  if [ "$COMP_CWORD" -eq 2 ] && [ -n "$subs" ] && [[ "$cur" != -* ]]; then',
    '    COMPREPLY=( $(compgen -W "$subs" -- "$cur") )',
    '  elif [[ "$cur" == -* ]]; then',
    '    COMPREPLY=( $(compgen -W "$flags" -- "$cur") )',
    '  else',
    '    COMPREPLY=( $(compgen -f -- "$cur") )',
    '  fi',
    '}',
    'complete -o default -F _typecad_pcb typecad-pcb pcb',
  ].join('\n');
}

/** One `'name:description'` line for `_describe`; colons in the description are escaped. */
function zshDescribed(name: string, summary: string): string {
  const escaped = summary.replace(/'/g, `'\\''`).replace(/:/g, '\\:');
  return `'${name}:${escaped}'`;
}

function zshScript(entries: CompletionEntry[]): string {
  const described = [
    ...entries.map((e) => `      ${zshDescribed(e.name, e.summary)}`),
    "      'help:Show help'",
  ].join('\n');
  const cases = entries
    .map((e) => `    ${e.name}) subs=(${e.subs.join(' ')}); flags=(${e.flags.join(' ')}) ;;`)
    .join('\n');
  return [
    '#compdef typecad-pcb pcb',
    '# typecad-pcb zsh completion — generated by `typecad-pcb completion zsh`',
    '(( $+functions[compdef] )) || { autoload -Uz compinit && compinit }',
    '_typecad_pcb() {',
    '  local -a cmds subs flags',
    '  if (( CURRENT == 2 )); then',
    '    cmds=(',
    described,
    '    )',
    "    _describe -t commands 'command' cmds",
    '    return',
    '  fi',
    `  flags=(${GLOBAL_COMPLETION_FLAGS.join(' ')})`,
    '  case "$words[2]" in',
    cases,
    '  esac',
    '  if (( CURRENT == 3 )) && (( ${#subs} )) && [[ "$words[CURRENT]" != -* ]]; then',
    '    compadd -a subs',
    '  elif [[ "$words[CURRENT]" == -* ]]; then',
    '    compadd -a flags',
    '  else',
    '    _files',
    '  fi',
    '}',
    'compdef _typecad_pcb typecad-pcb pcb',
  ].join('\n');
}

function pwshQuote(text: string): string {
  return `'${text.replace(/'/g, "''")}'`;
}

function pwshScript(entries: CompletionEntry[]): string {
  const list = (items: string[]) => `@(${items.map(pwshQuote).join(', ')})`;
  const table = entries
    .map((e) => `  ${pwshQuote(e.name)} = @{ subs = ${list(e.subs)}; flags = ${list(e.flags)} }`)
    .join('\n');
  return [
    '# typecad-pcb PowerShell completion — generated by `typecad-pcb completion pwsh`',
    '$script:typecadPcbCompletions = @{',
    table,
    '}',
    "Register-ArgumentCompleter -Native -CommandName 'typecad-pcb', 'pcb' -ScriptBlock {",
    '  param($wordToComplete, $commandAst, $cursorPosition)',
    '  $words = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.ToString() })',
    "  if ($wordToComplete -ne '') {",
    '    if ($words.Count -le 1) { $words = @() } else { $words = @($words[0..($words.Count - 2)]) }',
    '  }',
    '  $items = @()',
    '  if ($words.Count -eq 0) {',
    "    $items = @($script:typecadPcbCompletions.Keys) + 'help'",
    '  } else {',
    '    $entry = $script:typecadPcbCompletions[$words[0]]',
    '    if ($entry) {',
    "      if ($words.Count -eq 1 -and $entry.subs.Count -gt 0 -and -not $wordToComplete.StartsWith('-')) {",
    '        $items = $entry.subs',
    '      } else {',
    '        $items = $entry.flags',
    '      }',
    '    }',
    '  }',
    '  $items | Where-Object { $_ -like "$wordToComplete*" } | Sort-Object | ForEach-Object {',
    "    [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)",
    '  }',
    '}',
  ].join('\n');
}

export function completionScript(shell: Shell): string {
  const entries = completionEntries();
  if (shell === 'bash') return bashScript(entries);
  if (shell === 'zsh') return zshScript(entries);
  return pwshScript(entries);
}

export async function run(parsed: ParsedArgs): Promise<void> {
  const requested = parsed.positional[0];
  const shell = requested ? SHELL_NAMES[requested.toLowerCase()] : undefined;

  if (!shell) {
    const message = requested
      ? `Unknown shell '${requested}'. Use bash, zsh or pwsh.`
      : 'Name a shell: typecad-pcb completion <bash|zsh|pwsh>.';
    if (parsed.json) logger.out(JSON.stringify({ error: true, message, code: 'UNKNOWN_SHELL' }));
    else logger.error(`${message}\nSee typecad-pcb completion --help for how to install it.`);
    process.exit(2);
  }

  const script = completionScript(shell);
  if (parsed.json) {
    logger.out(JSON.stringify({ shell, script }));
  } else {
    // Straight to stdout: the script must survive --quiet and be pipeable.
    process.stdout.write(`${script}\n`);
  }
}
