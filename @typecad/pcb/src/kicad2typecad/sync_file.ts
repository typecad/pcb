// ---------------------------------------------------------------------------
// _sync.ts — typeCAD's machine-owned source sidecar: ONE grammar shared by
// every code-inserting path (the layout view's apply and the board import).
//
// Why a dedicated file: auto-inserted statements used to splice into
// hand-written code next to the constructs they target, and each tool did
// that surgery with its own reader. A sidecar that only ever holds
// tool-written statements in one canonical shape removes that class of
// fragile edits — and because syncBoard() is CALLED immediately before
// typecad.create(), everything it assigns always wins the code-order
// battle (component state is read at create() time, and public-field
// assignments after construction override constructor options).
//
// This module is the grammar: banner, scaffold, detection, insertion
// anchors, and the entry-file integration (import line, syncBoard() call,
// `...syncTracks` spread). It is deliberately dependency-free and pure so
// the vscode extension compiles a byte-identical copy (its build cannot
// reach across package roots) — a contract test pins the two copies
// together.
// ---------------------------------------------------------------------------

export const SYNC_FILE_NAME = '_sync.ts';
export const SYNC_FUNCTION_NAME = 'syncBoard';
export const SYNC_TRACKS_NAME = 'syncTracks';
export const SYNC_PARTS_PARAM = 'parts';
export const SYNC_TYPECAD_PARAM = 'typecad';

/**
 * The sidecar file name for a board: single-board projects keep the
 * original `_sync.ts`; a multi-board project (mother/daughter, board/jig)
 * gives each board its own `_sync.<stem>.ts` so the sidecars never collide.
 */
export function syncFileNameFor(stem?: string): string {
  return stem ? `_sync.${stem}.ts` : SYNC_FILE_NAME;
}

/** Is this base name a typeCAD sidecar (canonical or per-board)? */
export function isSyncFileName(name: string): boolean {
  return /^_sync(\.[A-Za-z0-9_$.-]+)?\.ts$/.test(name);
}

/** mm with up to 3 decimals, trailing zeros stripped — reads like hand-written code. */
export function syncFmt(n: number): string {
  return String(parseFloat(n.toFixed(3)));
}

export function syncFileBanner(): string {
  return [
    '// ---------------------------------------------------------------------------',
    '// _sync.ts — AUTO-GENERATED by typeCAD (layout apply / board import).',
    '//',
    '// Machine-owned: every statement here is placed by a tool, in the one',
    '// canonical shape this file is parsed back with. syncBoard() runs right',
    '// before the create() call in the entry file, so placements and',
    '// label layouts assigned on `parts` override the constructor options, and',
    '// routes pushed onto syncTracks reach the board through the',
    '// `...syncTracks` spread in create().',
    '//',
    '// Regenerate instead of editing — apply any layout edit or re-run the',
    '// import. Deleting the file is safe once the entry file\'s syncBoard()',
    '// call and `...syncTracks` spread are removed too.',
    '// ---------------------------------------------------------------------------',
    '',
  ].join('\n');
}

export interface SyncFileSections {
  /** placement / label assignment statements, each a full `parts.x… = { … };` line */
  placements?: string[];
  /** route statements: `const routeN = new TrackBuilder(…)` chains plus their collect pushes */
  routes?: string[];
}

/** The full canonical file. Statements arrive pre-indented (two spaces). */
export function renderSyncFile(sections: SyncFileSections): string {
  const placements = sections.placements ?? [];
  const routes = sections.routes ?? [];
  const body: string[] = [`  ${SYNC_TRACKS_NAME}.length = 0;`, ''];
  if (placements.length > 0) {
    body.push('  // --- auto placements (override constructor `pcb:` options) ---');
    body.push(...placements);
    body.push('');
  }
  if (routes.length > 0) {
    body.push('  // --- auto routes (reach the board via `...syncTracks` in create()) ---');
    body.push(...routes);
  }
  let bodyText = body.join('\n').replace(/\n+$/, '\n');
  if (!bodyText.endsWith('\n')) bodyText += '\n';
  return (
    syncFileBanner() +
    `import { TrackBuilder } from '@typecad/pcb';\n` +
    `import type { Component, PCB } from '@typecad/pcb';\n` +
    '\n' +
    `export const ${SYNC_TRACKS_NAME}: TrackBuilder[] = [];\n` +
    '\n' +
    `export function ${SYNC_FUNCTION_NAME}(${SYNC_TYPECAD_PARAM}: PCB, ${SYNC_PARTS_PARAM}: Record<string, Component>): void {\n` +
    bodyText +
    '}\n'
  );
}

/** Does this text carry the sync sidecar's function? (The banner alone may be quoted in docs.) */
export function isSyncFileText(text: string): boolean {
  return new RegExp(`export\\s+function\\s+${SYNC_FUNCTION_NAME}\\s*\\(`).test(text);
}

export interface SyncRange {
  start: number;
  end: number;
}

/**
 * A length-preserving structural shadow: comment bodies and string-literal
 * contents become spaces (quotes and newlines stay, so every offset and
 * line anchor maps 1:1 back to the real text). Structural scans — create()
 * lookup, brace/paren balance, argument insertion — run over this so prose
 * or string text that merely looks like code can never capture them.
 */
function structuralShadow(text: string): string {
  const out = text.split('');
  const blank = (i: number): void => {
    if (out[i] !== '\n') out[i] = ' ';
  };
  let i = 0;
  let quote: string | null = null;
  while (i < text.length) {
    const ch = text[i]!;
    if (quote) {
      if (ch === '\\' && i + 1 < text.length) {
        blank(i);
        blank(i + 1);
        i += 2;
        continue;
      }
      if (ch === quote) quote = null;
      else blank(i);
      i++;
    } else if (ch === "'" || ch === '"' || ch === '`') {
      quote = ch;
      i++;
    } else if (ch === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') {
        blank(i);
        i++;
      }
    } else if (ch === '/' && text[i + 1] === '*') {
      blank(i);
      blank(i + 1);
      i += 2;
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) {
        blank(i);
        i++;
      }
      if (i < text.length) {
        blank(i);
        blank(i + 1);
        i += 2;
      }
    } else {
      i++;
    }
  }
  return out.join('');
}

/** The syncBoard() body's INNER range (between the braces), or null when absent. */
export function syncFunctionBodyRange(text: string): SyncRange | null {
  // scanned over the structural shadow: braces inside strings (net names)
  // or comments must not tip the balance
  const shadow = structuralShadow(text);
  const head = new RegExp(`export\\s+function\\s+${SYNC_FUNCTION_NAME}\\s*\\(`).exec(shadow);
  if (!head) return null;
  let depth = 0;
  let paramClose = -1;
  for (let i = head.index + head[0].length - 1; i < shadow.length; i++) {
    const ch = shadow[i];
    if (ch === '(') depth++;
    else if (ch === ')') {
      depth--;
      if (depth === 0) {
        paramClose = i;
        break;
      }
    }
  }
  if (paramClose === -1) return null;
  const braceOpen = shadow.indexOf('{', paramClose);
  if (braceOpen === -1) return null;
  depth = 0;
  for (let i = braceOpen; i < shadow.length; i++) {
    const ch = shadow[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) return { start: braceOpen + 1, end: i };
    }
  }
  return null;
}

/** Start offset of the freshest line for a placement/label statement inside the body. */
export function syncPlacementInsertAt(text: string): number | null {
  const body = syncFunctionBodyRange(text);
  if (!body) return null;
  // regexes run over the shadowed slice (offsets align 1:1) so a
  // commented-out statement cannot pose as an anchor
  const slice = structuralShadow(text).slice(body.start, body.end);
  let anchor = -1;
  const assign = /^[ \t]*parts\.[A-Za-z_$][\w$]*\.(?:pcb|referenceLayout|valueLayout|fabLayout|fab)\s*=/gm;
  const reset = new RegExp(`^[ \\t]*${SYNC_TRACKS_NAME}\\.length\\s*=\\s*0\\s*;[ \\t]*$`, 'gm');
  for (const re of [assign, reset]) {
    const m = re.exec(slice);
    if (m) {
      const lineEnd = slice.indexOf('\n', m.index + m[0].length);
      anchor = lineEnd === -1 ? body.end : body.start + lineEnd + 1;
    }
    if (anchor !== -1) break; // first (topmost) match of THIS class; classes are tried in order
  }
  return anchor === -1 ? body.start : anchor;
}

/** Start offset of the freshest line for route declarations inside the body. */
export function syncRouteInsertAt(text: string): number | null {
  const body = syncFunctionBodyRange(text);
  if (!body) return null;
  const slice = structuralShadow(text).slice(body.start, body.end);
  let anchor = -1;
  const push = new RegExp(`^[ \\t]*${SYNC_TRACKS_NAME}\\.push\\(`, 'gm');
  let m: RegExpExecArray | null;
  while ((m = push.exec(slice)) !== null) {
    const lineEnd = slice.indexOf('\n', m.index + m[0].length);
    anchor = lineEnd === -1 ? body.end : body.start + lineEnd + 1;
  }
  if (anchor !== -1) return anchor;
  return syncPlacementInsertAt(text);
}

/** The collect statement emitted after a route declaration inside syncBoard(). */
export function syncPushStatement(name: string): string {
  return `  ${SYNC_TRACKS_NAME}.push(${name});`;
}

// --- entry-file integration ------------------------------------------------
//
// The ONLY lines the tools ever add to hand-written code: one import, one
// call right before typecad.create(), and (once routes exist) the
// `...syncTracks` spread inside create(). All three are canonical shapes,
// re-planned idempotently on every apply.

export interface SyncTextEdit {
  start: number;
  end: number;
  line: string;
}

export interface SyncEntryPlan {
  edits: SyncTextEdit[];
  /** the PCB instance receiver create() is called on (null: no create() found) */
  receiver: string | null;
}

/**
 * Locate `typecad.create(` and its balanced closing paren (null when
 * absent/unbalanced). Comment/string-aware via the structural shadow: a
 * banner or doc comment that mentions the call is not the call, and the
 * canonical `typecad` receiver is preferred so an earlier unrelated
 * `x.create(…)` cannot capture the wiring.
 */
function findCreateCallAt(text: string): { index: number; closeIndex: number; receiver: string } | null {
  const shadow = structuralShadow(text);
  const m =
    /(typecad)\s*\.\s*create\s*\(/.exec(shadow) ?? /([A-Za-z_$][\w$]*)\s*\.\s*create\s*\(/.exec(shadow);
  if (!m) return null;
  const open = shadow.indexOf('(', m.index);
  let depth = 0;
  for (let i = open; i < shadow.length; i++) {
    const ch = shadow[i];
    if (ch === '(') depth++;
    else if (ch === ')') {
      depth--;
      if (depth === 0) return { index: m.index, closeIndex: i, receiver: m[1]! };
    }
  }
  return null;
}

/**
 * Where an appended create() argument goes: after the last real token inside
 * the parens, skipping trailing whitespace, comments, and string contents
 * (the shadow blanks them) — a line comment or a `//` inside a string
 * argument must not end up between two commas.
 */
function createArgInsertion(text: string, open: number, close: number): { at: number; sep: string } {
  const shadow = structuralShadow(text);
  let at = open + 1;
  let lastTok = '(';
  for (let i = at; i < close; i++) {
    const ch = shadow[i]!;
    if (!/\s/.test(ch)) {
      at = i + 1;
      lastTok = ch;
    }
  }
  const sep = lastTok === '(' ? '' : lastTok === ',' ? ' ' : ', ';
  return { at, sep };
}

/**
 * Plan the entry file's sync integration: the sidecar import (named for the
 * board on multi-board projects), the `syncBoard(typecad, { …parts })` call
 * immediately before create(), and the `...syncTracks` spread inside create()
 * when routes need it. Every edit is a canonical rewrite — re-planning is
 * idempotent.
 */
export function planSyncEntryEdits(
  entryText: string,
  partsVars: string[],
  needTracks: boolean,
  stem?: string,
): SyncEntryPlan {
  const edits: SyncTextEdit[] = [];
  const create = findCreateCallAt(entryText);
  const receiver = create?.receiver ?? SYNC_TYPECAD_PARAM;
  // detection runs over the shadow (offsets align 1:1 with the real text):
  // a commented-out import, call, or spread is none of those
  const shadow = structuralShadow(entryText);
  const sidecarModule = `./${syncFileNameFor(stem).replace(/\.ts$/, '')}.js`;

  // import line — rewritten wholesale whenever it is ours. Lines are
  // located structurally on the shadow (specifiers' quotes survive, their
  // contents do not) and identified as OURS on the real text: a
  // commented-out import is not an import.
  const importNames = [SYNC_FUNCTION_NAME, ...(needTracks ? [SYNC_TRACKS_NAME] : [])];
  const canonicalImport = `import { ${importNames.join(', ')} } from '${sidecarModule}';`;
  const IMPORT_ANY = /import\s*\{[^}]*\}\s*from\s*['"][^'"]*['"]\s*;?/g;
  const oursRe = new RegExp(`['"][^'"]*_sync(?:\\.[A-Za-z0-9_$.-]+)?(?:\\.js)?['"]`);
  let ours: RegExpExecArray | null = null;
  let last: RegExpExecArray | null = null;
  for (let m: RegExpExecArray | null; (m = IMPORT_ANY.exec(shadow)) !== null; ) {
    last = m;
    if (oursRe.test(entryText.slice(m.index, m.index + m[0].length))) ours = m;
  }
  if (ours) {
    if (entryText.slice(ours.index, ours.index + ours[0].length) !== canonicalImport) {
      edits.push({ start: ours.index, end: ours.index + ours[0].length, line: canonicalImport });
    }
  } else {
    const at = last ? last.index + last[0].length : 0;
    const tail = last ? '\n' : '\n\n';
    edits.push({ start: at, end: at, line: tail + canonicalImport });
  }

  // call line — immediately before create(), parts map maintained wholesale
  const vars = [...new Set(partsVars)].sort();
  const mapText = vars.length > 0 ? `{ ${vars.join(', ')} }` : '{}';
  const callLine = (indent: string): string =>
    `${indent}${SYNC_FUNCTION_NAME}(${receiver}, ${mapText});`;
  const existingCall = /^([ \t]*)syncBoard\(\s*[A-Za-z_$][\w$]*\s*,\s*\{[^}]*\}\s*\);[ \t]*$/m.exec(shadow);
  if (existingCall) {
    const fresh = callLine(existingCall[1] ?? '');
    if (entryText.slice(existingCall.index, existingCall.index + existingCall[0].length) !== fresh) {
      edits.push({ start: existingCall.index, end: existingCall.index + existingCall[0].length, line: fresh });
    }
  } else if (create) {
    const lineStart = entryText.lastIndexOf('\n', create.index) + 1;
    const indent = /^[ \t]*/.exec(entryText.slice(lineStart, create.index))?.[0] ?? '';
    edits.push({ start: lineStart, end: lineStart, line: `${callLine(indent)}\n` });
  }

  // create() spread — `...syncTracks`, once, comment/string-aware
  let spreadEdit: SyncTextEdit | null = null;
  if (create && needTracks) {
    const args = entryText.slice(create.index, create.closeIndex + 1);
    if (!new RegExp(`\\.\\.\\.${SYNC_TRACKS_NAME}\\b`).test(shadow.slice(create.index, create.closeIndex + 1))) {
      const { at, sep } = createArgInsertion(entryText, entryText.indexOf('(', create.index), create.closeIndex);
      const gap = entryText.slice(at, create.closeIndex);
      const spacer = gap === '' || /^\s/.test(gap) ? '' : ' ';
      const rel = at - create.index;
      spreadEdit = {
        start: create.index,
        end: create.closeIndex + 1,
        line: args.slice(0, rel) + `${sep}...${SYNC_TRACKS_NAME}${spacer}${gap})`,
      };
    }
  }

  // a freshly-inserted call line and the create() rewrite share their offset
  // when create( starts its line — fold them into ONE replacement so the
  // edit list never carries overlapping ranges
  if (spreadEdit) {
    const callEdit = edits.find((e) => e.start === spreadEdit!.start && e.end === e.start && e.line.endsWith('\n'));
    if (callEdit) {
      spreadEdit.line = callEdit.line + spreadEdit.line;
      edits.splice(edits.indexOf(callEdit), 1);
    }
    edits.push(spreadEdit);
  }

  return { edits, receiver: create ? receiver : null };
}
